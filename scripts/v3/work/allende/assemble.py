"""Rebuild the fiche, run mechanical checks, write <key>_full_en.txt and split it into chunks for the fact-checkers.

Generated by scripts/v3/setup_medium.py from scripts/v3/templates/assemble.py (do not edit the copy in work/<key>/:
edit the template and re-run setup). Run: python3 scripts/v3/work/<key>/assemble.py
"""
import subprocess, re, html, os
SLUG = "agustin-allende"
TITLE = "Agustin Allende"
KEY = "allende"
G = os.path.dirname(os.path.abspath(__file__)) + '/'
R = os.path.abspath(os.path.join(G, '..', '..', '..', '..')) + '/'
print(subprocess.run(['python3', 'scripts/_enrich.py', SLUG], cwd=R, capture_output=True, text=True).stdout.strip()[-200:])
for p in [f'characters/{SLUG}/index.html', f'fr/personnages/{SLUG}/index.html']:
    s = open(R + p, encoding='utf-8').read()
    print(p, 'dashes:', s.count('—') + s.count('–'), 'rels:', s.count('<div class="rel">'), 'words:', len(re.sub(r'<[^>]+>', ' ', s).split()))
    print('  heading guillemets:', re.findall(r'<h[1-6][^>]*>[^<]*«', s)[:2])
    for u in sorted(set(re.findall(r'href="(/[^"#?]+)"', s))):
        if not (os.path.exists(R + u.lstrip('/') + 'index.html') or os.path.exists(R + u.lstrip('/'))):
            print('  BROKEN', u)
    for u in sorted(set(re.findall(r'src="((?:\.\./)+[^"?]+)"', s))):
        if not os.path.exists(os.path.join(R, os.path.dirname(p), u)):
            print('  MISSING', u)
s = open(R + f'characters/{SLUG}/index.html', encoding='utf-8').read()
body = s[s.find('<div class="profile__intro">'):s.find('<aside class="related"')]
txt = html.unescape(re.sub(r'\n\s*\n+', '\n', re.sub(r'<(h[2-4]|p|li|tr|summary|figcaption|blockquote|cite)[^>]*>', '\n', body)))
txt = re.sub(r'<[^>]+>', '', txt); txt = re.sub(r'\n\s*\n+', '\n', txt)
open(G + f'{KEY}_full_en.txt', 'w', encoding='utf-8').write(txt)
lines = txt.split('\n'); n = len(lines)
cuts = [0]
# split at section boundaries nearest to thirds (full tier; the medium tier then runs split2.py for 2 halves)
heads = [i for i, l in enumerate(lines) if l.strip() in ('Personality', 'Missions', 'Quotes', 'Development and performance', 'Trivia', 'Relationships')]
for frac in (1 / 3, 2 / 3):
    target = int(n * frac); cuts.append(min(heads, key=lambda i: abs(i - target)) if heads else target)
cuts.append(n); cuts = sorted(set(cuts))
for k in range(len(cuts) - 1):
    chunk = '\n'.join(lines[cuts[k]:cuts[k + 1]]); open(G + f'check{k + 1}.txt', 'w', encoding='utf-8').write(chunk)
    print(f'check{k + 1}.txt', len(chunk.split()), 'words')
print(subprocess.run(['python3', 'scripts/coverage.py', SLUG, TITLE], cwd=R, capture_output=True, text=True).stdout.split('=== Our fiche')[1:])
